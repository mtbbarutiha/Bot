type EmojiPickerProps = {
  open: boolean;
  onClose: () => void;
  onPick: (emoji: string) => void;
};

export function EmojiPicker({ open, onClose, onPick }: EmojiPickerProps) {
  const [categoryId, setCategoryId] = useState(EMOJI_CATEGORIES[0]!.id);
  const panelRef = useRef<HTMLDivElement>(null);

  const active = useMemo(
    () => EMOJI_CATEGORIES.find((c) => c.id === categoryId) ?? EMOJI_CATEGORIES[0]!,
    [categoryId],
  );

  useEffect(() => {
    if (!open) return;
    const onKey = (e: KeyboardEvent) => {
      if (e.key === 'Escape') onClose();
    };
    const onDoc = (e: MouseEvent) => {
      const t = e.target as Node;
      if (panelRef.current?.contains(t)) return;
      const emojiBtn = (e.target as HTMLElement | null)?.closest?.('.tg-emoji-btn');
      if (emojiBtn) return;
      onClose();
    };
    document.addEventListener('keydown', onKey);
    document.addEventListener('mousedown', onDoc);
    return () => {
      document.removeEventListener('keydown', onKey);
      document.removeEventListener('mousedown', onDoc);
    };
  }, [open, onClose]);

  if (!open) return null;

  return (
    <div
      ref={panelRef}
      className="tg-emoji-picker"
      role="dialog"
      aria-label="انتخاب ایموجی"
      dir="ltr"
    >
      <div className="tg-emoji-picker-tabs" role="tablist" aria-label="دسته‌بندی ایموجی">
        {EMOJI_CATEGORIES.map((cat) => (
          <button
            key={cat.id}
            type="button"
            role="tab"
            aria-selected={cat.id === categoryId}
            className={`tg-emoji-tab${cat.id === categoryId ? ' is-active' : ''}`}
            onClick={() => setCategoryId(cat.id)}
            title={cat.id}
          >
            {cat.label}
          </button>
        ))}
      </div>
      <div className="tg-emoji-picker-grid" role="listbox" aria-label={active.id}>
        {active.emojis.map((emoji) => (
          <button
            key={`${active.id}-${emoji}`}
            type="button"
            className="tg-emoji-cell"
            role="option"
            onClick={() => onPick(emoji)}
            aria-label={emoji}
          >
            {emoji}
          </button>
        ))}
      </div>
    </div>
  );
}
